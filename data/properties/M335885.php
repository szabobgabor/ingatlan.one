## Új építésű, kulcsrakész üzlethelyiség Csorna központjának közelében

Csornán, a **Liszt Ferenc utca és a Kórház utca sarkán**, új építésű társasház földszintjén kínálok megvételre egy **25 m²-es, utcai bejárattal rendelkező üzlethelyiséget**.

Az ingatlan elhelyezkedése kiváló: **a belváros rövid sétával elérhető**, a környéken pedig a közterületi parkolás ingyenes. Mérete és kialakítása miatt ideális lehet többek között **irodának, szépségápolási vagy egészségügyi szolgáltatásnak, bemutatóteremnek, kisebb üzletnek vagy egyéb szolgáltató tevékenységhez**.

Az üzlethelyiség **új építésű és kulcsrakész állapotban kerül átadásra**, így a leendő tulajdonosnak nem egy szerkezetkész helyiséget kell saját költségén befejeznie.

### Főbb műszaki jellemzők

* 30 cm-es Porotherm falazat
* **15 cm grafitos homlokzati hőszigetelés**
* Kömmerling 76AD nyílászárók, **3 rétegű üvegezéssel**
* korszerű, **levegő-víz hőszivattyús fűtési rendszer**
* használati melegvíz-ellátás gázkazánnal
* **1 db felszerelt klímaberendezés**
* korszerű villamos hálózat
* Schrack Visio szerelvények
* LED világítás
* fehérre festett falak
* **A++ energetikai besorolás**

Az ingatlanhoz **1 db saját gépkocsibeálló** tartozik, amelynek megvásárlása a helyiséggel együtt történik.

